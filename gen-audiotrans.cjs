/* Generates js/audio-transition-presets.js from Filmora's audio transitions.
 *
 * Source: assets/resources/transition/<dir>/description.json
 *   { "type": "audio_transition", "display_name": …, "unique_name": "audio/blender/…" }
 *
 * NOTE: the JSON also advertises "thumb" / "video" files, but those are NOT in
 * the dump (no thumb.png / test.mp4 anywhere under resources/transition). So the
 * picker draws its own curve previews instead of pretending to have artwork.
 *
 * Run: node gen-audiotrans.cjs
 */
const fs = require("fs");
const path = require("path");

const DIR = "assets/resources/transition";
const OUT = "js/audio-transition-presets.js";

/* The curve each unique_name denotes. These are the standard crossfade shapes —
 * the native Filmora DSP behind them is a DLL we cannot load, so we implement the
 * maths the name promises and say so in the UI. */
const CURVE = {
  "audio/blender/transition-fade": "linear",
  "audio/blender/transition-xe-constant-gain": "constantGain",
  "audio/blender/transition-xe-constant-power": "constantPower",
  "audio/blender/transition-xe-exponential-fade": "exponential",
  "audio/blender/transition-xe-logarithmic-fade": "logarithmic",
  "audio/blender/transition-dealiasing": "dealiasing",
  "audio/blender/simple-mix": "mix",
};

const LABEL = {
  "audio/blender/transition-fade": "Fade",
  "audio/blender/transition-xe-constant-gain": "Constant Gain",
  "audio/blender/transition-xe-constant-power": "Constant Power",
  "audio/blender/transition-xe-exponential-fade": "Exponential Fade",
  "audio/blender/transition-xe-logarithmic-fade": "Logarithmic Fade",
  "audio/blender/transition-dealiasing": "De-aliasing",
  "audio/blender/simple-mix": "Simple Mix",
};

/* What each one actually does, shown in the picker. */
const NOTE = {
  linear: "Straight ramp. Simple, but correlated audio dips in the middle of the crossfade.",
  constantGain: "Linear crossfade — the two gains always sum to 1. Can dip on correlated material.",
  constantPower: "Sine/cosine crossfade; gains sum in POWER, so perceived level holds steady. The safe default.",
  exponential: "Slow start, quick finish — gain grows exponentially, so it stays quiet then arrives fast.",
  logarithmic: "Quick start, slow finish — the exact mirror of exponential.",
  dealiasing: "Equal-power shaping smoothed to avoid the discontinuities that cause zipper/alias artefacts.",
  mix: "No crossfade: both clips play at full level through the overlap.",
};

const out = [];
for (const dir of fs.readdirSync(DIR).sort()) {
  const file = path.join(DIR, dir, "description.json");
  if (!fs.existsSync(file)) continue;
  let j;
  try { j = JSON.parse(fs.readFileSync(file, "utf8")); } catch { continue; }
  if (j.type !== "audio_transition") continue;
  const uniq = j.unique_name || "";
  const curve = CURVE[uniq] || "constantPower";
  out.push({
    id: uniq,
    dir,
    label: LABEL[uniq] || j.display_name || dir,
    displayName: j.display_name || dir,
    curve,
    note: NOTE[curve] || "",
  });
}

if (!out.length) { console.error("no audio transitions found"); process.exit(1); }

const body =
  "/* GENERATED by gen-audiotrans.cjs — do not edit by hand.\n" +
  " * Filmora audio transitions, from assets/resources/transition/<dir>/description.json.\n" +
  " *\n" +
  " * The native DSP is a DLL we cannot load, and the thumb.png / test.mp4 that\n" +
  " * description.json advertises are NOT in the dump — so each entry carries the\n" +
  " * standard crossfade curve its name denotes, and the picker draws the curve\n" +
  " * itself rather than pretending to have Filmora's artwork.\n" +
  " *\n" +
  " * Re-run `node gen-audiotrans.cjs` after changing the asset dump.\n" +
  " */\n\n" +
  "export const AUDIO_TRANSITIONS = " + JSON.stringify(out, null, 2) + ";\n\n" +
  "const BY_ID = new Map(AUDIO_TRANSITIONS.map((t) => [t.id, t]));\n" +
  "export function audioTransitions() { return AUDIO_TRANSITIONS; }\n" +
  "export function audioTransitionById(id) { return BY_ID.get(id) || null; }\n" +
  "export const DEFAULT_AUDIO_TRANSITION = \"audio/blender/transition-xe-constant-power\";\n";

fs.writeFileSync(OUT, body, "utf8");
console.log("wrote " + OUT + "  " + (body.length / 1024).toFixed(1) + " KB");
console.log("transitions: " + out.length);
out.forEach(t => console.log("  " + t.label.padEnd(20) + " " + t.curve));
