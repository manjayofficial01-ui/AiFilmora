/** Names of every token a preset can override (so we can undo them cleanly). */
const PRESET_TOKEN_NAMES = (() => {
  const names = new Set();
  for (const p of Object.values(THEME_PRESETS)) Object.keys(p.tokens).forEach((k) => names.add(k));
  return Array.from(names);
})();

export function applyThemePreset(name) {
  const preset = THEME_PRESETS[name];
  if (!preset || typeof document === "undefined") return false;
  const root = document.documentElement;
  for (const [k, v] of Object.entries(preset.tokens)) root.style.setProperty(k, v);
  root.setAttribute("data-theme-preset", name);
  return true;
}

/** Undo any inline preset overrides so the stylesheet defaults take over again. */
export function clearThemePreset() {
  if (typeof document === "undefined") return;
  const root = document.documentElement;
  PRESET_TOKEN_NAMES.forEach((k) => root.style.removeProperty(k));
  root.removeAttribute("data-theme-preset");
}

export function isThemePreset(name) {
  return Object.prototype.hasOwnProperty.call(THEME_PRESETS, name);
}

export function listThemePresets() {
  return Object.entries(THEME_PRESETS).map(([id, p]) => ({ id, label: p.label }));
}

