function keyOfCaption(label) {
  const norm = label.toLowerCase().replace(/[_-]+/g, " ").replace(/\s+/g, " ").trim();
  if (ANIM_TO_KEY[norm] !== undefined) return ANIM_TO_KEY[norm];
  for (const k of Object.keys(ANIM_TO_KEY)) {
    if (k === "no animation") continue;
    if (norm.includes(k)) return ANIM_TO_KEY[k];
  }
  return "fade";
}

let _capAnims = null;
export function captionAnimations() {
  if (_capAnims) return _capAnims;
  const out = [];
  for (const [kind, list] of Object.entries(CAPTION_FILES)) {
    list.forEach((file, i) => {
      const label = file.replace(/\.(png|xml)$/i, "").trim();
      out.push({
        id: kind + ":" + i,
        kind,
        label,
        thumb: CAPTION_DIRS[kind] + encodeURIComponent(file),
        key: keyOfCaption(label),
        file,
      });
    });
  }
  _capAnims = out;
  return _capAnims;
}

