const WEIGHT_TOKENS = [
  ["Thin", 100], ["ExtraLight", 200], ["UltraLight", 200], ["Light", 300],
  ["Regular", 400], ["Normal", 400], ["Medium", 500], ["SemiBold", 600], ["DemiBold", 600],
  ["Bold", 700], ["ExtraBold", 800], ["UltraBold", 800], ["Black", 900], ["Heavy", 900],
  ["Fat", 900],
];
const STYLE_TOKENS = ["Italic", "Oblique", "Slant"];

function parseFontFilename(file) {
  const base = file.replace(/\.(ttf|otf)$/i, "");
  // Filmora ships de-duplicated copies as "Name-Weight_0.ttf" / "_1" — the numeric
  // suffix is a copy counter, not part of the family name.
  const cleaned = base.replace(/^\d+_+/, "").replace(/_\d+$/, "");
  let family = cleaned;
  let weight = 400;
  let style = "normal";
  const tokens = cleaned.split(/[\s_-]+/).filter(Boolean);
  while (tokens.length > 1) {
    const last = tokens[tokens.length - 1];
    const wt = WEIGHT_TOKENS.find(([w]) => last.toLowerCase() === w.toLowerCase());
    if (wt) { weight = wt[1]; tokens.pop(); continue; }
    if (STYLE_TOKENS.some((s) => last.toLowerCase() === s.toLowerCase())) {
      style = last.toLowerCase(); tokens.pop(); continue;
    }
    break;
  }
  family = tokens.join(" ");
  if (family.endsWith(" Regular")) family = family.slice(0, -9);
  if (!family) family = base;
  return { family, weight, style, label: cleaned };
}

let _fonts = null;
export function fonts() {
  if (_fonts) return _fonts;
  _fonts = FONT_FILES.map((file) => {
    const { family, weight, style, label } = parseFontFilename(file);
    const url = BASE + "Fonts/" + encodeURIComponent(file);
    const id = family.toLowerCase().replace(/[^a-z0-9]+/g, "-") + "-" + weight + (style !== "normal" ? "i" : "");
    return { id, family, weight, style, file, url, label };
  });
  const seen = new Set();
  _fonts = _fonts.filter((f) => (seen.has(f.id) ? false : seen.add(f.id)));
  return _fonts;
}

let _fontsInjected = false;
export function injectFontFace(doc = (typeof document !== "undefined" ? document : null)) {
  if (_fontsInjected || !doc) return;
  _fontsInjected = true;
  const css = fonts()
    .map((f) =>
      `@font-face{font-family:"${f.family}";font-style:${f.style};font-weight:${f.weight};font-display:swap;src:url("${f.url}") format("${f.file.toLowerCase().endsWith(".otf") ? "opentype" : "truetype"}")}`
    )
    .join("");
  let style = doc.getElementById("assets-bridge-fonts");
  if (!style) {
    style = doc.createElement("style");
    style.id = "assets-bridge-fonts";
    doc.head.appendChild(style);
  }
  style.textContent = css;
}

